describe('format codes, as Excel formats them', () => {
  for (const [group, cases] of Object.entries(EXCEL)) {
    describe(group, () => {
      for (const [code, value, expected] of cases) {
        it(`${JSON.stringify(code)} of ${String(value)} is ${JSON.stringify(expected)}`, () => {
          const text = formatCode(value, code, { date1904: true });
          expect(isError(text) ? text.code : text).toBe(expected);
        });
      }
    });
  }
});

describe('format codes, in the 1900 system', () => {
  it('reads a serial as the sheet does', () => {
    expect(formatCode(46289, 'yyyy-mm-dd')).toBe('2026-09-24');
    expect(formatCode(60, 'd mmm yyyy')).toBe('29 Feb 1900');
  });

  it('refuses a negative date, as Excel does', () => {
    expect(formatCode(-1, 'yyyy')).toMatchObject({ code: '#VALUE!' });
  });

  it('formats a number written as text as the number', () => {
    expect(formatCode('1234.5', '#,##0.00')).toBe('1,234.50');
  });

  it('passes an error through', () => {
    expect(formatCode(NA, '0')).toMatchObject({ code: '#N/A' });
  });

  it('writes General in eleven characters at most', () => {
    expect(formatGeneral(2 / 3)).toBe('0.666666667');
    expect(formatGeneral(123456789012)).toBe('1.23457E+11');
  });
});
